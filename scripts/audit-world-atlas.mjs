import fs from 'node:fs'
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
const page = await context.newPage()
const errors = [], checks = []
page.on('pageerror', e => errors.push(e.message))
const origin = process.env.AUDIT_ORIGIN ?? 'http://127.0.0.1:4173'
const go = async path => { await page.goto(origin + path, { waitUntil: 'domcontentloaded' }); await page.locator('.top-nav-bar').waitFor() }
try {
  await go('/atlas')
  await page.getByRole('heading', { name: 'The world, one bite at a time.' }).waitFor()
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  assert.ok(await page.getByRole('button', { name: 'Zoom out', exact: true }).isEnabled())
  await page.getByRole('button', { name: 'Reset view', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('button[aria-label="Zoom out"]').disabled)
  const cluster = page.locator('.atlas-map-pin-hitarea[aria-label^="Explore"]').first()
  await cluster.press('Enter')
  await page.getByRole('region', { name: 'Places in this cluster' }).waitFor()
  await page.getByRole('button', { name: 'Close choices' }).click()
  checks.push('map zoom/reset and keyboard-accessible cluster choices')
  await page.getByRole('button', { name: 'Ramen', exact: true }).click()
  await page.locator('.atlas-place-list button').filter({ hasText: 'Japan' }).click()
  await page.getByLabel('Look closer: region or city').selectOption('Sapporo, Hokkaido')
  await page.locator('.atlas-food-card').filter({ hasText: 'Sapporo Miso Ramen' }).click()
  await page.locator('.atlas-style-story').waitFor()
  assert.match(await page.locator('.atlas-style-story').innerText(), /miso|Miso/)
  await page.getByText('Variations on the tradition', { exact: true }).click()
  assert.match(await page.locator('.atlas-style-story').innerText(), /Butter and corn/)
  await page.getByText('The deeper story', { exact: true }).click()
  assert.match(await page.locator('.atlas-style-story').innerText(), /1950s/)
  const styleUrl = page.url()
  await page.reload()
  await page.locator('.atlas-style-story').waitFor()
  assert.equal(page.url(), styleUrl)
  assert.equal(await page.getByLabel('Look closer: region or city').inputValue(), 'Sapporo, Hokkaido')
  await page.getByRole('link', { name: 'Explore the full story & recipe →' }).click()
  await page.locator('.content-journey').waitFor()
  assert.ok(page.url().endsWith('/ramen/ramen/ramen_sapporo_miso'))
  await page.goBack()
  await page.locator('.atlas-style-story').waitFor()
  assert.equal(page.url(), styleUrl)
  assert.equal(await page.locator('.taste-this-place').count(), 0)
  checks.push('world → Japan → ramen → Sapporo → miso → story/recipe, reload, Back and travel gating')
  await go('/atlas?country=Mexico&food=cookie_marranitos')
  await page.locator('.atlas-style-story').waitFor()
  assert.ok((await page.locator('.taste-this-place a').getAttribute('href')).includes('/mexico-city-by-cruiser-bike-'))
  await go('/atlas?country=Brazil&food=cake_bolo_de_rolo')
  await page.locator('.atlas-style-story').waitFor()
  assert.equal(await page.locator('.taste-this-place').count(), 0)
  checks.push('explicit destination links; no Rio handoff for Pernambuco-specific cake')
  await go('/atlas?country=Italy')
  await page.getByLabel('Look closer: region or city').selectOption('Siena, Tuscany')
  assert.match(await page.locator('.atlas-food-grid').innerText(), /Panforte/)
  await page.getByRole('button', { name: 'Noodles', exact: true }).click()
  assert.ok(!page.url().includes('Italy'))
  await page.getByLabel('Where are you curious about?').fill('Atlantis')
  await page.getByText('No places match. Try another name or food world.').waitFor()
  checks.push('Italian regional styles; incompatible world filter and empty-place recovery')
  await go('/cookies')
  const cardPhoto = page.locator('a[href="/cookies/encyclopedia"] img')
  await cardPhoto.waitFor()
  assert.match(await cardPhoto.getAttribute('src'), /cookie_marranitos.webp/)
  await go('/cookies/encyclopedia')
  await page.locator('.page-hero-band-image').waitFor()
  assert.match(await page.locator('.page-hero-band-image').getAttribute('src'), /cookie_marranitos.webp/)
  await page.locator('.page-hero-band-image').evaluate(img => img.decode())
  await page.screenshot({ path: 'reports/cookie-encyclopedia-new-photo.png' })
  await go('/cookies/workshop')
  await page.locator('.page-hero-band').waitFor()
  const workshopSrc = await page.locator('.page-hero-band-image').getAttribute('src').catch(() => '')
  assert.ok(!workshopSrc.includes('cookie_marranitos.webp'))
  checks.push('distinct, loaded Encyclopedia photography on landing card and banner')
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await go('/atlas')
    await page.locator('.atlas-trail').first().waitFor()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.screenshot({ path: `reports/world-atlas-${width}.png`, fullPage: true })
    await go('/atlas?country=Japan&world=ramen&region=Sapporo%2C+Hokkaido&food=ramen_sapporo_miso')
    await page.locator('.atlas-style-story').waitFor()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    assert.equal(await page.locator('.atlas-country-story').evaluate(el => getComputedStyle(el).animationName), 'none')
  }
  checks.push('320/390/1440px layouts and reduced-motion preference')
  assert.deepEqual(errors, [])
  fs.writeFileSync('reports/world-atlas-interactions.json', JSON.stringify({ checks, errors }, null, 2))
  console.log(JSON.stringify({ checks, errors }, null, 2))
} finally { await browser.close() }
